#!/usr/bin/env python3
"""Compose delegate-kit agent definitions from base templates + optional integration fragments.

This is the Kimchi port of the delegate-kit compose script. It adapts the ORIGINAL
kit's templates (from the delegate-kit Claude Code plugin) into a Kimchi agents
directory — typically <project>/.kimchi/agents — by splicing each enabled integration
fragment's tool grants and prose at the `<!-- delegate-kit:integrations -->` marker.

Templates keep their original Claude Code tool names (Read, Bash, Task, ...) as-is:
this script does NOT rename them to Kimchi spellings. The composed files are a
starting point — wire the tool names up for your own agents before use.

The target agents dir already holds your custom agents. compose never overwrites an
existing file it did not itself write (tracked in .delegate-kit-stamp.json): such a
file is refused with an error unless --force is given. Re-running with the same
--agents-dir overwrites the files compose wrote last time.

Integration detection is re-scoped to Kimchi: --list reads ~/.config/kimchi/harness/mcp.json
(if present) to report which fragments' MCP servers are configured.

Stdlib only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

MARKER = "<!-- delegate-kit:integrations -->"
# Agents whose whole value is their lack of tools; no fragment may widen them.
STARVED = frozenset({"director", "thinker", "super-thinker"})
STAMP_NAME = ".delegate-kit-stamp.json"
# Models the director may be pinned to (`--director-model`). Both are top-tier; which one
# judges better changes with each release, so it's the user's pick, not ours.
DIRECTOR_MODELS = ("fable", "opus")
GENERATED_NOTE = (
    "<!-- Generated by delegate-kit (Kimchi port). Do not edit by hand — "
    "rerun `dk compose` with the same flags to change integrations. -->"
)

FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
AGENT_SECTION_RE = re.compile(r"^## agent:([A-Za-z0-9_-]+)\s*$", re.M)


# --------------------------------------------------------------------------- paths

def kimchi_dk_dir() -> Path:
    """The kit dir everything flows from: $KIMCHI_DK_DIR, else ~/.local/share/kimchi/delegate-kit."""
    env = os.environ.get("KIMCHI_DK_DIR", "").strip()
    if env:
        return Path(env).expanduser()
    return Path.home() / ".local" / "share" / "kimchi" / "delegate-kit"


def default_agents_dir() -> Path | None:
    """<cwd>/.kimchi/agents when <cwd>/.kimchi exists, else None."""
    cwd = Path.cwd()
    if (cwd / ".kimchi").is_dir():
        return cwd / ".kimchi" / "agents"
    return None


def kimchi_mcp_servers() -> list[str]:
    """MCP server names from the Kimchi harness config (~/.config/kimchi/harness/mcp.json), if present."""
    path = Path.home() / ".config" / "kimchi" / "harness" / "mcp.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    servers = data.get("mcpServers") if isinstance(data, dict) else None
    if not isinstance(servers, dict):
        return []
    return sorted(str(k) for k in servers)


def mcp_available(detect_mcp: str, servers: list[str]) -> bool:
    """A fragment's detect_mcp server (or its bare name) appears in the Kimchi MCP config."""
    if not detect_mcp:
        return False
    return any(
        s == detect_mcp or s.endswith("__" + detect_mcp) or s.endswith(":" + detect_mcp)
        for s in servers
    )


# --------------------------------------------------------------------------- parsing


def split_frontmatter(text: str) -> tuple[dict, str]:
    """Return (frontmatter dict, body). Values are raw strings; keys keep their case."""
    m = FRONTMATTER_RE.match(text)
    if not m:
        raise ValueError("file has no YAML frontmatter")
    fm: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            # This is a single-line `key: value` parser, not YAML. A list item
            # ("  - Read") has no colon and would vanish silently, taking a
            # fragment's whole tool grant with it — so say so instead.
            raise ValueError(
                f"frontmatter line {line.strip()!r} is not `key: value`. "
                "Lists must be written inline and comma-separated "
                "(`tools: Read, Grep`), not as YAML list items"
            )
        key, _, value = line.partition(":")
        fm[key.strip()] = value.strip()
    return fm, text[m.end():]


def split_list(value: str | None) -> list[str]:
    if not value:
        return []
    value = value.strip()
    if value in ("[]", ""):
        return []
    return [item.strip() for item in value.split(",") if item.strip()]


def parse_fragment(path: Path) -> dict:
    fm, body = split_frontmatter(path.read_text(encoding="utf-8"))
    name = fm.get("name") or path.stem
    sections: dict[str, str] = {}
    matches = list(AGENT_SECTION_RE.finditer(body))
    shared = body[: matches[0].start()] if matches else body
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(body)
        sections[m.group(1)] = body[m.end():end].strip()
    return {
        "name": name,
        "title": fm.get("title", name),
        "url": fm.get("url", ""),
        "detect_mcp": fm.get("detect_mcp", ""),
        "detect_bin": fm.get("detect_bin", ""),
        "agents": split_list(fm.get("agents")),
        "tools": {
            key[len("tools@"):] if key.startswith("tools@") else "*": split_list(value)
            for key, value in fm.items()
            if key == "tools" or key.startswith("tools@")
        },
        "shared": shared.strip(),
        "sections": sections,
        "source": str(path),
    }


def discover(dirs: list[Path]) -> dict[str, dict]:
    """Later directories win, so a user fragment can override a shipped one by name."""
    found: dict[str, dict] = {}
    for d in dirs:
        if not d.is_dir():
            continue
        for path in sorted(d.glob("*.md")):
            try:
                frag = parse_fragment(path)
            except ValueError as exc:
                print(f"warning: skipping {path}: {exc}", file=sys.stderr)
                continue
            found[frag["name"]] = frag
    return found


# ------------------------------------------------------------------------ composing


def compose(
    template_text: str,
    agent: str,
    fragments: list[dict],
    models: dict | None = None,
) -> str:
    """`models` maps agent name -> a `model:` value replacing the template's pin."""
    fm, body = split_frontmatter(template_text)
    applicable = [f for f in fragments if not f["agents"] or agent in f["agents"]]

    # One pass, because a fragment's grants and its prose have to stay paired:
    # the only thing worth failing on is a fragment that does both — lands a tool
    # *and* loses the prose that teaches it. Counting the two independently blames
    # whichever fragment happened to grant something for prose it never wrote.
    tools = split_list(fm.get("tools"))
    # `tools` is mutated in place by the grant loop below; keep what the template
    # itself asked for, so an error can name exactly what a fragment would add.
    declared = list(tools)
    granters, blocks, prose_from = [], [], []
    for frag in applicable:
        granted = frag["tools"].get(agent, frag["tools"].get("*", []))
        added = []
        for tool in granted:
            if tool not in tools:
                tools.append(tool)
                added.append(tool)

        text = (frag["sections"].get(agent) or frag["shared"]).strip()
        if text:
            blocks.append(text)
            prose_from.append(frag["name"])
        if added:
            granters.append(frag["name"])

    # These three are defined by what they cannot do: the director delegates every
    # file touch because it has no way to make one, and the reasoners know only what
    # you typed. Widening any of them does not add a feature, it removes the reason
    # to use it. Enforced by name rather than by "this template happens to have no
    # marker", so that re-adding one cannot quietly reopen the hole.
    if agent in STARVED:
        if MARKER in body:
            raise ValueError(
                f"{agent} carries {MARKER}, but it must take no integrations: its "
                f"value is what it cannot do. Remove the marker from the template."
            )
        if granters:
            raise ValueError(
                f"{agent}: {', '.join(granters)} would grant it "
                f"{', '.join(t for t in tools if t not in declared)}. "
                f"This agent takes no integrations at all. Scope the fragment with "
                f"`agents:` so it does not apply here."
            )

    if MARKER not in body and granters:
        # No marker means this template takes no integrations. A grant would leave
        # the agent holding tools nothing ever taught it to use. Checked before any
        # prose handling, because a fragment that grants a tool and writes no prose
        # slipped straight past the prose-gated check this replaced.
        raise ValueError(
            f"{agent}: {', '.join(granters)} grant(s) tools, but this template takes "
            f"no integrations (it has no {MARKER}). Scope the fragment with `agents:` "
            f"so it does not apply here."
        )

    if MARKER in body:
        replacement = "\n\n".join(blocks) if blocks else ""
        body = body.replace(MARKER, replacement, 1)
        # collapse the blank-line pileup a removed marker leaves behind
        body = re.sub(r"\n{3,}", "\n\n", body)
    elif blocks:
        # Prose with no grant riding on it — anything that granted a tool already
        # raised above. The agents that take no integrations carry no marker, so a
        # fragment omitting `agents:` (meaning "all of them") lands here. Nothing
        # that matters is lost, but don't drop it silently.
        print(
            f"note: {agent}: prose from {', '.join(prose_from)} not applied: the template has "
            f"no {MARKER}. Add `agents:` to the fragment to limit where it applies.",
            file=sys.stderr,
        )

    lines = ["---"]
    for key, value in fm.items():
        if key == "tools":
            # `tools: []` does NOT mean "no tools". Measured on Claude Code 2.1.263:
            # an empty list (and an empty string) resolves to every MCP tool in the
            # environment, while an absent `tools:` line grants every built-in. A
            # genuinely tool-less agent is not expressible — the harness refuses to
            # spawn one ("would be spawned with zero tools — refusing"). So the
            # minimum is one real tool, and emitting an empty value is always a bug.
            if not tools:
                raise ValueError(
                    f"{agent} resolves to no tools. `tools: []` is not "
                    f"\"no tools\": it grants every MCP tool in the environment, "
                    f"and the harness refuses to spawn a genuinely tool-less agent. "
                    f"Give the template an explicit minimal grant, e.g. `tools: Skill`."
                )
            value = ", ".join(tools)
        elif key == "model" and models and agent in models:
            value = models[agent]
        lines.append(f"{key}: {value}")
    if "tools" not in fm and granters:
        # Deliberately not written out: an absent `tools:` means "inherit every
        # tool", so these grants are already in effect. Emitting them here would
        # turn an unrestricted agent into one limited to just this list. It still
        # looks like a silent drop from the outside, so say what happened.
        print(
            f"note: {agent} declares no `tools:` line, so it inherits every tool; "
            f"the grants from {', '.join(granters)} already apply and are not written "
            "out. Give the template an explicit `tools:` line to restrict it.",
            file=sys.stderr,
        )
    lines.append("---")
    lines.append("")
    lines.append(GENERATED_NOTE)
    return "\n".join(lines) + "\n" + body.rstrip() + "\n"


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def fragment_list_view(frag: dict, servers: list[str]) -> dict:
    d = {k: frag[k] for k in ("name", "title", "url", "detect_mcp", "detect_bin", "agents", "source")}
    d["mcp_present"] = mcp_available(d["detect_mcp"], servers)
    d["bin_present"] = bool(d["detect_bin"] and shutil.which(d["detect_bin"]))
    return d


# ----------------------------------------------------------------------------- main


def main() -> int:
    here = Path(__file__).resolve().parent.parent
    dk = kimchi_dk_dir()
    agents_dir = default_agents_dir()
    ap = argparse.ArgumentParser(
        prog="dk compose",
        description="Adapt the delegate-kit agent templates into a Kimchi agents dir by "
        "splicing enabled integration fragments. The original kit templates keep their "
        "Claude Code tool names as-is (they are not renamed); the composed files are a "
        "starting point you wire up in your own agents. Existing agent files compose did "
        "not write are refused unless --force is given.",
    )
    ap.add_argument(
        "--agents-dir",
        type=Path,
        default=None,
        help="agents directory to write into (default: <cwd>/.kimchi/agents if <cwd>/.kimchi exists)",
    )
    ap.add_argument(
        "--templates",
        type=Path,
        default=None,
        help="directory of base templates (default: $KIMCHI_DK_DIR/templates/agents, else "
        "<this kit>/templates/agents if present). Point it at the original delegate-kit "
        "repo's templates/agents; template tool names are kept as-is",
    )
    ap.add_argument(
        "--integrations",
        type=Path,
        nargs="*",
        default=None,
        help="fragment directories, later ones override earlier by fragment name "
        "(default: $KIMCHI_DK_DIR/integrations)",
    )
    ap.add_argument("--enable", default="", help="comma-separated fragment names ('' = none)")
    ap.add_argument("--list", action="store_true", help="print discoverable fragments as JSON")
    ap.add_argument(
        "--director-model",
        choices=DIRECTOR_MODELS,
        default=None,
        help="model the director is pinned to (default: the previous compose's choice, else fable)",
    )
    ap.add_argument(
        "--force",
        action="store_true",
        help="overwrite existing agent files that compose did not write (default: refuse "
        "and change nothing)",
    )
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-backup", action="store_true")
    args = ap.parse_args()

    if agents_dir is None and args.agents_dir is None:
        print("error: no .kimchi directory in the current working directory; pass --agents-dir", file=sys.stderr)
        return 2
    agents_dir = args.agents_dir or agents_dir
    user_integrations = dk / "integrations"
    integration_dirs = list(args.integrations) if args.integrations is not None else [user_integrations]
    templates_dir = args.templates
    if templates_dir is None:
        local = here / "templates" / "agents"
        templates_dir = local if local.is_dir() else dk / "templates" / "agents"

    fragments = discover(integration_dirs)

    if args.list:
        servers = kimchi_mcp_servers()
        print(json.dumps(
            {
                "agents_dir": str(agents_dir),
                "integration_dirs": [str(d) for d in integration_dirs],
                "user_integration_dir": str(user_integrations),
                "mcp_servers": servers,
                "mcp_config": str(Path.home() / ".config" / "kimchi" / "harness" / "mcp.json"),
                "fragments": [fragment_list_view(f, servers) for f in fragments.values()],
                "agents": sorted(p.stem for p in templates_dir.glob("*.md")),
            },
            indent=2,
        ))
        return 0

    # Deduped and sorted: a repeated name splices the same fragment's prose twice,
    # and two orderings of one set produce different files for the same request.
    requested = sorted(dict.fromkeys(split_list(args.enable)))
    unknown = [name for name in requested if name not in fragments]
    if unknown:
        print(f"error: unknown fragment(s): {', '.join(unknown)}", file=sys.stderr)
        print(f"known: {', '.join(sorted(fragments)) or 'none found'}", file=sys.stderr)
        if not fragments:
            print("note: no fragments discovered in %s; point --integrations at the original "
                  "delegate-kit repo's integrations/ (or populate $KIMCHI_DK_DIR/integrations)"
                  % ", ".join(str(d) for d in integration_dirs), file=sys.stderr)
        return 2
    enabled = [fragments[name] for name in requested]

    # Sticky: a re-run of compose (say, to add an integration) must not quietly put the
    # director back on the default. Only an explicit flag changes the pin.
    stamp_path = agents_dir / STAMP_NAME
    try:
        prior = json.loads(stamp_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        prior = {}
    prev_files = prior.get("files") if isinstance(prior, dict) and isinstance(prior.get("files"), dict) else {}
    director_model = args.director_model
    if director_model is None:
        pm = prior.get("director_model") if isinstance(prior, dict) else None
        director_model = pm if pm in DIRECTOR_MODELS else None
    if director_model not in DIRECTOR_MODELS:
        director_model = "fable"
    models = {"director": director_model}

    templates = sorted(templates_dir.glob("*.md"))
    if not templates:
        print(f"error: no templates in {templates_dir} (copy delegate-kit's templates/agents there, "
              "or pass --templates <path to delegate-kit>/templates/agents)", file=sys.stderr)
        return 2

    # Compose every agent BEFORE writing any of them. These definitions are a set:
    # a run that writes four and then fails on the fifth leaves the agents dir
    # holding a mix of old and new files — and when the failure is a bad tool
    # grant, one of the files already on disk is the compromised one. Validating
    # everything first means a failed compose changes nothing at all.
    composed, stamp_files = [], {}
    for template in templates:
        agent = template.stem
        try:
            text = compose(template.read_text(encoding="utf-8"), agent, enabled, models)
        except ValueError as exc:
            print(f"error: {exc}", file=sys.stderr)
            print("error: nothing written; no agent definition was changed.", file=sys.stderr)
            return 1
        applied = [f["name"] for f in enabled if not f["agents"] or agent in f["agents"]]
        stamp_files[template.name] = {"sha": sha(text), "integrations": applied}
        composed.append((template, text, applied))

    # Never overwrite the user's own agents: only files compose wrote last time
    # (same sha as recorded in the stamp) may be replaced without --force.
    refusals = []
    for template, text, _ in composed:
        target = agents_dir / template.name
        if not target.exists():
            continue
        owned = prev_files.get(template.name)
        current = sha(target.read_text(encoding="utf-8"))
        if not isinstance(owned, dict) or owned.get("sha") != current:
            refusals.append(target.name)

    # A refused run changes nothing at all: check before any write or backup.
    if refusals and not args.dry_run and not args.force:
        print("error: refusing to overwrite existing agent file(s) that compose did not write: "
              + ", ".join(sorted(refusals)), file=sys.stderr)
        print(f"error: your custom agents in {agents_dir} already exist; pass --force to replace "
              "them (previous versions are backed up to .delegate-kit-backup). nothing written.",
              file=sys.stderr)
        return 1

    agents_dir.mkdir(parents=True, exist_ok=True)
    backup = agents_dir / ".delegate-kit-backup"
    written = []

    for template, text, applied in composed:
        target = agents_dir / template.name
        if args.dry_run:
            if target.name in refusals:
                print(f"would refuse {target}  [exists, not compose-owned; pass --force]")
            else:
                print(f"would write {target}  [{', '.join(applied) or 'no integrations'}]")
            continue

        if target.exists() and target.name in refusals:
            # only reachable with --force (or --dry-run): back up the user's file first
            if not args.dry_run and not args.no_backup and target.read_text(encoding="utf-8") != text:
                backup.mkdir(parents=True, exist_ok=True)
                shutil.copy2(target, backup / template.name)
        elif target.exists() and not args.no_backup and target.read_text(encoding="utf-8") != text:
            backup.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, backup / template.name)
        with open(target, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        written.append(target)
        print(f"wrote {target}  [{', '.join(applied) or 'no integrations'}]")


    if args.dry_run:
        print(f"director model: {director_model}")
        return 0

    stamp_path.write_text(
        json.dumps(
            {
                "generated_by": "delegate-kit (kimchi port)",
                "plugin_root": str(here),
                "enabled": requested,
                "director_model": director_model,
                "files": stamp_files,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    if backup.exists():
        print(f"\nprevious versions backed up to {backup}")
    print(f"\n{len(written)} agent definition(s) written to {agents_dir}")
    print(f"enabled integrations: {', '.join(requested) or '(none)'}")
    print(f"director model: {director_model}")
    print("Restart Kimchi (or start a new session) for the changes to load.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())