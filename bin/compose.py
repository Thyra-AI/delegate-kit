#!/usr/bin/env python3
"""Compose delegate-kit agent definitions from base templates + optional integration fragments.

The plugin ships integration-agnostic templates (built-in tools only). Each optional
integration — Serena, graphify, or one you write yourself — lives in a fragment that
declares the tools it grants and the prose that teaches an agent to use them. This
script unions the tool lists and splices the prose at the `<!-- delegate-kit:integrations -->`
marker, then writes finished agent definitions to the output directory.

Stdlib only. Run `--list` to see what's discoverable, `--enable` to compose.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

MARKER = "<!-- delegate-kit:integrations -->"
# Agents whose whole value is their lack of tools; no fragment may widen them.
STARVED = frozenset({"director", "thinker", "super-thinker"})
STAMP_NAME = ".delegate-kit-stamp.json"
GENERATED_NOTE = (
    "<!-- Generated by delegate-kit. Do not edit by hand — "
    "rerun /delegate-kit:setup to change integrations. -->"
)

FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
AGENT_SECTION_RE = re.compile(r"^## agent:([A-Za-z0-9_-]+)\s*$", re.M)


# --------------------------------------------------------------------------- parsing


def split_frontmatter(text: str) -> tuple[dict, str]:
    """Return (frontmatter dict, body). Values are raw strings; keys keep their case."""
    m = FRONTMATTER_RE.match(text)
    if not m:
        raise ValueError("file has no YAML frontmatter")
    fm: dict[str, str] = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            # This is a single-line `key: value` parser, not YAML. A list item
            # ("  - Read") has no colon and would vanish silently, taking a
            # fragment's whole tool grant with it — so say so instead.
            raise ValueError(
                f"frontmatter line {line.strip()!r} is not `key: value`. "
                "Lists must be written inline and comma-separated "
                "(`tools: Read, Grep`), not as YAML list items"
            )
        key, _, value = line.partition(":")
        fm[key.strip()] = value.strip()
    return fm, text[m.end():]


def split_list(value: str | None) -> list[str]:
    if not value:
        return []
    value = value.strip()
    if value in ("[]", ""):
        return []
    return [item.strip() for item in value.split(",") if item.strip()]


def parse_fragment(path: Path) -> dict:
    fm, body = split_frontmatter(path.read_text(encoding="utf-8"))
    name = fm.get("name") or path.stem
    sections: dict[str, str] = {}
    matches = list(AGENT_SECTION_RE.finditer(body))
    shared = body[: matches[0].start()] if matches else body
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(body)
        sections[m.group(1)] = body[m.end():end].strip()
    return {
        "name": name,
        "title": fm.get("title", name),
        "url": fm.get("url", ""),
        "detect_mcp": fm.get("detect_mcp", ""),
        "detect_bin": fm.get("detect_bin", ""),
        "agents": split_list(fm.get("agents")),
        "tools": {
            key[len("tools@"):] if key.startswith("tools@") else "*": split_list(value)
            for key, value in fm.items()
            if key == "tools" or key.startswith("tools@")
        },
        "shared": shared.strip(),
        "sections": sections,
        "source": str(path),
    }


def discover(dirs: list[Path]) -> dict[str, dict]:
    """Later directories win, so a user fragment can override a shipped one by name."""
    found: dict[str, dict] = {}
    for d in dirs:
        if not d.is_dir():
            continue
        for path in sorted(d.glob("*.md")):
            try:
                frag = parse_fragment(path)
            except ValueError as exc:
                print(f"warning: skipping {path}: {exc}", file=sys.stderr)
                continue
            found[frag["name"]] = frag
    return found


# ------------------------------------------------------------------------ composing


def compose(template_text: str, agent: str, fragments: list[dict]) -> str:
    fm, body = split_frontmatter(template_text)
    applicable = [f for f in fragments if not f["agents"] or agent in f["agents"]]

    # One pass, because a fragment's grants and its prose have to stay paired:
    # the only thing worth failing on is a fragment that does both — lands a tool
    # *and* loses the prose that teaches it. Counting the two independently blames
    # whichever fragment happened to grant something for prose it never wrote.
    tools = split_list(fm.get("tools"))
    granters, blocks, prose_from = [], [], []
    for frag in applicable:
        granted = frag["tools"].get(agent, frag["tools"].get("*", []))
        added = []
        for tool in granted:
            if tool not in tools:
                tools.append(tool)
                added.append(tool)

        text = (frag["sections"].get(agent) or frag["shared"]).strip()
        if text:
            blocks.append(text)
            prose_from.append(frag["name"])
        if added:
            granters.append(frag["name"])

    # These three are defined by what they cannot do: the director delegates every
    # file touch because it has no way to make one, and the reasoners know only what
    # you typed. Widening any of them does not add a feature, it removes the reason
    # to use it. Enforced by name rather than by "this template happens to have no
    # marker", so that re-adding one cannot quietly reopen the hole.
    if agent in STARVED:
        if MARKER in body:
            raise ValueError(
                f"{agent} carries {MARKER}, but it must take no integrations: its "
                f"value is what it cannot do. Remove the marker from the template."
            )
        if granters:
            raise ValueError(
                f"{agent}: {', '.join(granters)} would grant it {', '.join(t for t in tools if t not in split_list(fm.get('tools')))}. "
                f"This agent takes no integrations at all. Scope the fragment with "
                f"`agents:` so it does not apply here."
            )

    if MARKER not in body and granters:
        # No marker means this template takes no integrations. A grant would leave
        # the agent holding tools nothing ever taught it to use. Checked before any
        # prose handling, because a fragment that grants a tool and writes no prose
        # slipped straight past the prose-gated check this replaced.
        raise ValueError(
            f"{agent}: {', '.join(granters)} grant(s) tools, but this template takes "
            f"no integrations (it has no {MARKER}). Scope the fragment with `agents:` "
            f"so it does not apply here."
        )

    if MARKER in body:
        replacement = "\n\n".join(blocks) if blocks else ""
        body = body.replace(MARKER, replacement, 1)
        # collapse the blank-line pileup a removed marker leaves behind
        body = re.sub(r"\n{3,}", "\n\n", body)
    elif blocks:
        # Prose with no grant riding on it — anything that granted a tool already
        # raised above. The agents that take no integrations carry no marker, so a
        # fragment omitting `agents:` (meaning "all of them") lands here. Nothing
        # that matters is lost, but don't drop it silently.
        print(
            f"note: {agent}: prose from {', '.join(prose_from)} not applied: the template has "
            f"no {MARKER}. Add `agents:` to the fragment to limit where it applies.",
            file=sys.stderr,
        )

    lines = ["---"]
    for key, value in fm.items():
        if key == "tools":
            # `tools: []` does NOT mean "no tools". Measured on Claude Code 2.1.263:
            # an empty list (and an empty string) resolves to every MCP tool in the
            # environment, while an absent `tools:` line grants every built-in. A
            # genuinely tool-less agent is not expressible — the harness refuses to
            # spawn one ("would be spawned with zero tools — refusing"). So the
            # minimum is one real tool, and emitting an empty value is always a bug.
            if not tools:
                raise ValueError(
                    f"{agent} resolves to no tools. `tools: []` is not "
                    f"\"no tools\": it grants every MCP tool in the environment, "
                    f"and the harness refuses to spawn a genuinely tool-less agent. "
                    f"Give the template an explicit minimal grant, e.g. `tools: Skill`."
                )
            value = ", ".join(tools)
        lines.append(f"{key}: {value}")
    if "tools" not in fm and granters:
        # Deliberately not written out: an absent `tools:` means "inherit every
        # tool", so these grants are already in effect. Emitting them here would
        # turn an unrestricted agent into one limited to just this list. It still
        # looks like a silent drop from the outside, so say what happened.
        print(
            f"note: {agent} declares no `tools:` line, so it inherits every tool; "
            f"the grants from {', '.join(granters)} already apply and are not written "
            "out. Give the template an explicit `tools:` line to restrict it.",
            file=sys.stderr,
        )
    lines.append("---")
    lines.append("")
    lines.append(GENERATED_NOTE)
    return "\n".join(lines) + "\n" + body.rstrip() + "\n"


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


# ----------------------------------------------------------------------------- main


def main() -> int:
    here = Path(__file__).resolve().parent.parent
    default_out = Path.home() / ".claude" / "agents"
    user_integrations = Path.home() / ".claude" / "delegate-kit" / "integrations"

    ap = argparse.ArgumentParser(prog="delegate-kit compose")
    ap.add_argument("--templates", type=Path, default=here / "templates" / "agents")
    ap.add_argument(
        "--integrations",
        type=Path,
        nargs="*",
        default=[here / "integrations", user_integrations],
        help="fragment directories, later ones override earlier by fragment name",
    )
    ap.add_argument("--out", type=Path, default=default_out)
    ap.add_argument("--enable", default="", help="comma-separated fragment names ('' = none)")
    ap.add_argument("--list", action="store_true", help="print discoverable fragments as JSON")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-backup", action="store_true")
    args = ap.parse_args()

    fragments = discover(args.integrations)

    if args.list:
        print(json.dumps(
            {
                "integration_dirs": [str(d) for d in args.integrations],
                "user_integration_dir": str(user_integrations),
                "out": str(args.out),
                "fragments": [
                    {
                        k: frag[k]
                        for k in ("name", "title", "url", "detect_mcp", "detect_bin", "agents", "source")
                    }
                    for frag in fragments.values()
                ],
                "agents": sorted(p.stem for p in args.templates.glob("*.md")),
            },
            indent=2,
        ))
        return 0

    requested = split_list(args.enable)
    unknown = [name for name in requested if name not in fragments]
    if unknown:
        print(f"error: unknown fragment(s): {', '.join(unknown)}", file=sys.stderr)
        print(f"known: {', '.join(sorted(fragments)) or '(none)'}", file=sys.stderr)
        return 2
    enabled = [fragments[name] for name in requested]

    templates = sorted(args.templates.glob("*.md"))
    if not templates:
        print(f"error: no templates in {args.templates}", file=sys.stderr)
        return 2

    args.out.mkdir(parents=True, exist_ok=True)
    backup = args.out / ".delegate-kit-backup"
    written, stamp_files = [], {}

    # Compose every agent BEFORE writing any of them. These definitions are a set:
    # a run that writes four and then fails on the fifth leaves ~/.claude/agents
    # holding a mix of old and new files -- and when the failure is a bad tool
    # grant, one of the files already on disk is the compromised one. Validating
    # everything first means a failed compose changes nothing at all.
    composed = []
    for template in templates:
        agent = template.stem
        try:
            text = compose(template.read_text(encoding="utf-8"), agent, enabled)
        except ValueError as exc:
            print(f"error: {exc}", file=sys.stderr)
            print("error: nothing written; no agent definition was changed.", file=sys.stderr)
            return 1
        applied = [f["name"] for f in enabled if not f["agents"] or agent in f["agents"]]
        stamp_files[template.name] = {"sha": sha(text), "integrations": applied}
        composed.append((template, text, applied))

    for template, text, applied in composed:
        target = args.out / template.name
        if args.dry_run:
            print(f"would write {target}  [{', '.join(applied) or 'no integrations'}]")
            continue

        if target.exists() and not args.no_backup and target.read_text(encoding="utf-8") != text:
            backup.mkdir(parents=True, exist_ok=True)
            shutil.copy2(target, backup / template.name)
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
        print(f"wrote {target}  [{', '.join(applied) or 'no integrations'}]")

    if args.dry_run:
        return 0

    (args.out / STAMP_NAME).write_text(
        json.dumps(
            {
                "generated_by": "delegate-kit",
                "plugin_root": str(here),
                "enabled": requested,
                "files": stamp_files,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    if backup.exists():
        print(f"\nprevious versions backed up to {backup}")
    print(f"\n{len(written)} agent definition(s) written to {args.out}")
    print(f"enabled integrations: {', '.join(requested) or '(none)'}")
    print("Restart Claude Code (or start a new session) for the changes to load.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
